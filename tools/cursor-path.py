#!/usr/bin/env python3
"""Mouse path for a Claude-recorded walkthrough (tools/cdp.mjs record). Chrome's screencast has no
cursor, so the engine draws one from the logged hover/click positions.

  python3 tools/cursor-path.py <slug>

Reads videos/<slug>/source/rec/*/events.json (same order as source/raw/*), offsets each part by the
raw part durations (= the joined screen.mp4 timeline) and writes engine/src/videos/<slug>/cursor.ts:
moves {t0, t1, x, y} (glide to x,y between t0 and t1) and clicks {t, x, y} — source seconds, source px.
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
slug = sys.argv[1]
src = ROOT / "videos" / slug / "source"
recs = sorted(p for p in (src / "rec").iterdir() if (p / "events.json").exists())
raws = sorted(list((src / "raw").glob("*.mp4")) + list((src / "raw").glob("*.mov")))
assert len(recs) == len(raws), f"{len(recs)} recordings vs {len(raws)} raw parts"

GLIDE, PRESS = 0.35, 0.06  # cdp.mjs: glide 0.35 s, mouse down→up 60 ms before the event is logged
moves, clicks, offset = [], [], 0.0
for rec, raw in zip(recs, raws):
    meta = json.loads((rec / "events.json").read_text())
    k = meta["scale"]  # CSS px -> source px
    t0 = offset + meta["t0Offset"]
    start = next(e for e in meta["events"] if e["type"] == "start")["cursor"]
    moves.append({"t0": round(offset, 3), "t1": round(offset, 3), "x": round(start["x"] * k), "y": round(start["y"] * k)})
    for e in meta["events"]:
        if e["type"] not in ("hover", "click"):
            continue
        arrive = t0 + e["t"] - (PRESS if e["type"] == "click" else 0)
        x, y = round(e["x"] * k), round(e["y"] * k)
        moves.append({"t0": round(arrive - GLIDE, 3), "t1": round(arrive, 3), "x": x, "y": y})
        if e["type"] == "click":
            clicks.append({"t": round(arrive, 3), "x": x, "y": y})
    dur = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(raw)],
                         capture_output=True, text=True, check=True).stdout
    offset += float(dur)

out = ROOT / "engine" / "src" / "videos" / slug / "cursor.ts"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(
    "// Generated by tools/cursor-path.py — do not edit. Source seconds / source px of screen.mp4.\n"
    "import type { CursorPath } from \"../../lib/video\";\n\n"
    f"export const CURSOR: CursorPath = {json.dumps({'moves': moves, 'clicks': clicks})};\n"
)
print(f"{out.relative_to(ROOT)}: {len(moves)} moves, {len(clicks)} clicks over {offset:.2f}s")
for c in clicks:
    print(f"  click {c['t']:7.3f}s  ({c['x']}, {c['y']})")
