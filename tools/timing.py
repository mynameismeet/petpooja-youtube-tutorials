#!/usr/bin/env python3
"""Write engine/src/videos/<slug>/timing.ts from the locked mix (audio/mix/timeline.json).
  python3 tools/timing.py <slug>"""
import json, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
slug = sys.argv[1]
t = json.loads((ROOT / "videos" / slug / "audio/mix/timeline.json").read_text())
L = ",\n".join(f'  {l["id"]}: {{ start: {l["start"]}, end: {l["end"]} }}' for l in t["lines"])
S = ",\n".join(f'  {{ name: "{s["name"]}", at: {s["at"]} }}' for s in t["sfx"])
out = ROOT / "engine/src/videos" / slug / "timing.ts"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(f"""// Generated by tools/timing.py from videos/{slug}/audio/mix/timeline.json — do not edit.
// Every time is in OUTPUT seconds of the locked mix.
export const AUDIO_DURATION = {t["duration"]};

export const LINES = {{
{L},
}} as const;

export const SFX = [
{S},
] as const;
""")
print(f"{out.relative_to(ROOT)}: {len(t['lines'])} lines, {len(t['sfx'])} sfx, {t['duration']:.2f}s")
